from manimera import *


# ======================================================================================================================
# DEMO ATOM ROTATE SCENE
# ======================================================================================================================


class DemoAtomRotate(ManimeraScene):

    # CREATE METHOD ====================================================================================================

    def create(self):
        atom = BohrAtom(AtomType.Oganesson, atom_scale=5)
        self.play(AtomRotate(atom), run_time=2)


# ======================================================================================================================
# ENTRY POINT
# ======================================================================================================================

if __name__ == "__main__":
    ManimeraRender()

